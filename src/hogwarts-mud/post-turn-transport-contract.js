import { z } from 'zod';

import {
    APPEARANCE_SLOT_VALUES,
    LOCAL_MATERIAL_PERSISTENCE_VALUES,
    MATERIAL_EVENT_TYPES,
    MATERIAL_OPERATIONS,
} from '../../public/scripts/extensions/hogwarts-mud/material-schema.js';
import {
    POST_TURN_JSON_SCHEMA,
} from '../../public/scripts/extensions/hogwarts-mud/domain/post-turn-semantic-contract.js';

const confidenceSchema =
    z.number().min(0).max(1);
const temporalKinds = [
    'absolute_clock',
    'relative_duration',
    'named_time',
    'schedule',
    'calendar_date',
];
const temporalRelations = [
    'none',
    'before',
    'after',
    'until',
    'till',
    'later',
    'earlier',
    'ago',
    'past',
];
const perceptionShape = {
    version:
        z.literal(1),
    visualScope:
        z.enum([
            'none',
            'target',
            'nearby',
            'room',
            'area',
        ]),
    audibleScope:
        z.enum([
            'none',
            'target',
            'nearby',
            'room',
            'adjacent',
        ]),
    salience:
        z.enum([
            'subtle',
            'normal',
            'notable',
            'major',
        ]),
    attribution:
        z.enum([
            'clear',
            'ambiguous',
            'unknown',
        ]),
    concealment:
        z.enum([
            'none',
            'attempted',
            'successful',
        ]),
    directParticipantActorIds:
        z.array(
            z.string()
                .max(96),
        ).max(16),
    evidenceText:
        z.string()
            .min(1)
            .max(500),
    confidence:
        confidenceSchema,
    source:
        z.literal(
            'post_turn_observer',
        ),
};
const materialEventSchema =
    z.object({
        type:
            z.enum(
                MATERIAL_EVENT_TYPES,
            ),
        actorId:
            z.string().max(96),
        objectTextEn:
            z.string().max(300),
        sourceTextEn:
            z.string().max(300),
        targetTextEn:
            z.string().max(300),
        valueTextEn:
            z.string().max(300),
        previousValueTextEn:
            z.string().max(300),
        resultTextEn:
            z.string().max(500),
        quantity:
            z.number()
                .int()
                .min(1)
                .max(1_000)
                .nullable(),
        operation:
            z.enum(
                MATERIAL_OPERATIONS,
            ),
        slot:
            z.enum(
                APPEARANCE_SLOT_VALUES,
            ),
        hand:
            z.enum([
                'left',
                'right',
                'both',
                'unspecified',
            ]),
        persistence:
            z.enum(
                LOCAL_MATERIAL_PERSISTENCE_VALUES,
            ),
        sourceKind:
            z.enum([
                'player',
                'narrative',
            ]),
        evidenceText:
            z.string().max(500),
        confidence:
            confidenceSchema,
    }).strict();
const actorUpdateSchema =
    z.object({
        actorId:
            z.string().max(96),
        currentActivityEn:
            z.string().max(500),
        presence:
            z.enum([
                'unchanged',
                'present',
                'absent',
            ]),
        roomId:
            z.string().max(96),
        evidenceText:
            z.string().max(500),
        confidence:
            confidenceSchema,
    }).strict();
const temporalClaimSchema =
    z.object({
        kind:
            z.enum(
                temporalKinds,
            ),
        evidenceText:
            z.string()
                .min(1)
                .max(500),
        clock:
            z.string()
                .max(5),
        durationMinutes:
            z.number()
                .int()
                .min(0)
                .max(10_080),
        relation:
            z.enum(
                temporalRelations,
            ),
        confidence:
            confidenceSchema,
    }).strict();

export const postTurnResultSchema =
    z.object({
        schemaVersion:
            z.literal(1),
        materialEvents:
            z.array(
                materialEventSchema,
            ).max(16),
        actorUpdates:
            z.array(
                actorUpdateSchema,
            ).max(16),
        inventoryObservationRequired:
            z.boolean(),
        perception:
            z.object(
                perceptionShape,
            ).strict(),
        temporalClaims:
            z.array(
                temporalClaimSchema,
            ).max(16),
    }).strict();

export const postTurnJsonSchema =
    POST_TURN_JSON_SCHEMA;
