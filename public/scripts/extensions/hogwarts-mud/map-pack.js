const exit = (
    from,
    to,
    direction,
    kind = 'passage',
    minutes = 1,
    conditions = [],
    reverseConditions = conditions,
) => ({
    from,
    to,
    direction,
    kind,
    minutes,
    conditions,
    ...(reverseConditions !== conditions
        ? {
            reverseConditions,
        }
        : {}),
});

const deepFreeze = value => {
    if (!value || typeof value !== 'object' || Object.isFrozen(value)) {
        return value;
    }
    Object.values(value).forEach(deepFreeze);
    return Object.freeze(value);
};

