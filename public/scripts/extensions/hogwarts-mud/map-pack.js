export function findPresetLocalMapInText(text) {
    const source = String(text || '').toLocaleLowerCase();
    if (!source) {
        return null;
    }
    for (const [mapId, aliases] of Object.entries(LOCAL_MAP_ALIASES)) {
        if (aliases.some(alias => source.includes(alias.toLocaleLowerCase()))) {
            return PRESET_LOCAL_MAPS[mapId];
        }
    }
    return null;
}
