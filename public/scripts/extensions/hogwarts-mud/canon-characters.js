function deriveCanonSettingTags(character) {
    const override =
        CANON_SETTING_TAG_OVERRIDES[
            character.id
        ];
    if (override) return [...override];
    const tags = new Set();
    const house = String(
        character.house || '',
    ).toLocaleLowerCase();
    const role = String(
        character.roleEn || '',
    ).toLocaleLowerCase();
    const skills = String(
        character.skillsEn || '',
    ).toLocaleLowerCase();
    const affiliations = String(
        character.affiliationsEn || '',
    ).toLocaleLowerCase();
    if (house.includes('gryffindor')) {
        tags.add('adventurous');
        tags.add('rebellious');
    }
    if (house.includes('ravenclaw')) {
        tags.add('intellectual');
        tags.add('cautious');
    }
    if (house.includes('hufflepuff')) {
        tags.add('steady');
        tags.add('compassionate');
    }
    if (house.includes('slytherin')) {
        tags.add('ambitious');
        tags.add('cautious');
    }
    if (
        /auror|seeker|beater|duell|defence|defense/
            .test(`${role} ${skills}`)
    ) {
        tags.add('adventurous');
    }
    if (
        /prefect|minister|leader|head|captain/
            .test(
                `${role} ${skills} ${affiliations}`,
            )
    ) {
        tags.add('ambitious');
    }
    if (
        /healer|herbology|care|nurse|teacher/
            .test(`${role} ${skills}`)
    ) {
        tags.add('compassionate');
        tags.add('steady');
    }
    if (
        /barman|bartender|shop|student|singer|commentator/
            .test(role)
    ) {
        tags.add('social');
    }
    if (
        /joke|prank|dance|entertain/
            .test(`${role} ${skills}`)
    ) {
        tags.add('mischievous');
    }
    if (
        /seer|ghost|unspeakable|mystery|parseltongue/
            .test(`${role} ${skills}`)
    ) {
        tags.add('mysterious');
    }
    if (!tags.size) tags.add('steady');
    return [...tags].slice(0, 5);
}

function parseCanonYearRange(value) {
    const years = [
        ...String(value || '')
            .matchAll(
                /(1[0-9]{3}|20[0-9]{2})\b/g,
            ),
    ].map(match => Number(match[1]));
    if (!years.length) {
        return {
            birthYearMin: null,
            birthYearMax: null,
            estimatedBirthYear: null,
        };
    }
    const birthYearMin = Math.min(...years);
    const birthYearMax = Math.max(...years);
    return {
        birthYearMin,
        birthYearMax,
        estimatedBirthYear:
            Math.round(
                (
                    birthYearMin +
                    birthYearMax
                ) / 2,
            ),
    };
}

function getRelativeAgeBand(
    actorAge,
    playerAge,
) {
    if (
        !Number.isFinite(actorAge) ||
        !Number.isFinite(playerAge)
    ) {
        return 'unknown';
    }
    const delta = actorAge - playerAge;
    if (delta <= -6) return 'much_younger';
    if (delta <= -2) return 'younger_peer';
    if (delta <= 1) return 'same_age';
    if (delta <= 5) return 'older_peer';
    return 'older_generation';
}

export function getCanonSettingProfile(
    value,
    {
        worldYear = null,
        playerAge = null,
    } = {},
) {
    const character =
        typeof value === 'object'
            ? value
            : findCanonCharacter(value);
    if (!character) return null;
    const years = parseCanonYearRange(
        character.born,
    );
    const estimatedAge =
        Number.isFinite(worldYear) &&
        years.estimatedBirthYear !== null
            ? worldYear -
                years.estimatedBirthYear
            : null;
    return {
        ...character,
        fixedBirthText:
            character.born || '',
        ...years,
        estimatedAge,
        relativeAgeBand:
            getRelativeAgeBand(
                estimatedAge,
                playerAge,
            ),
        settingTags:
            deriveCanonSettingTags(
                character,
            ),
    };
}

export function recommendCanonCharacters({
    worldYear,
    playerAge,
    storyPreferences = {},
    locationText = '',
    excludeIds = [],
    limit = 12,
} = {}) {
    const excluded = new Set(excludeIds);
    const tone = String(
        storyPreferences.tone ||
        'balanced',
    );
    const agePreference = String(
        storyPreferences
            .relativeAgePreference ||
        'peer_focused',
    );
    const focuses = new Set(
        storyPreferences
            .relationshipFocus || [],
    );
    const desiredTags = new Set(
        tone === 'adventure'
            ? [
                'adventurous',
                'rebellious',
                'mischievous',
            ]
            : tone === 'mystery'
                ? [
                    'intellectual',
                    'mysterious',
                    'cautious',
                ]
                : tone === 'social'
                    ? [
                        'social',
                        'compassionate',
                        'mischievous',
                    ]
                    : [
                        'adventurous',
                        'social',
                        'intellectual',
                        'compassionate',
                    ],
    );
    const schoolContext =
        /hogwarts|train|express|platform|school|class|castle/i
            .test(locationText);
    return CANON_PLAYABLE_CHARACTER_CATALOG
        .filter(character =>
            !excluded.has(character.id))
        .map(character => {
            const profile =
                getCanonSettingProfile(
                    character,
                    {
                        worldYear,
                        playerAge,
                    },
                );
            const diedYear =
                parseCanonYearRange(
                    character.died,
                ).estimatedBirthYear;
            if (
                Number.isFinite(
                    diedYear,
                ) &&
                Number.isFinite(
                    worldYear,
                ) &&
                diedYear < worldYear
            ) {
                return null;
            }
            if (
                Number.isFinite(
                    profile
                        .estimatedBirthYear,
                ) &&
                profile
                    .estimatedBirthYear >
                    worldYear
            ) {
                return null;
            }
            if (
                schoolContext &&
                /student/i.test(
                    String(
                        profile.roleEn ||
                        '',
                    ),
                ) &&
                Number.isFinite(
                    profile.estimatedAge,
                ) &&
                (
                    profile.estimatedAge <
                        11 ||
                    profile.estimatedAge >
                        18
                )
            ) {
                return null;
            }
            if (
                agePreference ===
                    'peer_focused' &&
                profile.relativeAgeBand ===
                    'unknown'
            ) {
                return null;
            }
            let score = 0;
            const reasons = [];
            const matchingTags =
                profile.settingTags
                    .filter(tag =>
                        desiredTags.has(tag));
            const requiredToneTags =
                tone === 'adventure'
                    ? [
                        'adventurous',
                        'rebellious',
                        'mischievous',
                    ]
                    : tone === 'mystery'
                        ? [
                            'intellectual',
                            'mysterious',
                        ]
                        : tone === 'social'
                            ? [
                                'social',
                                'compassionate',
                            ]
                            : [];
            if (
                requiredToneTags.length &&
                !profile.settingTags.some(
                    tag =>
                        requiredToneTags
                            .includes(tag))
            ) {
                return null;
            }
            score +=
                matchingTags.length * 9;
            if (matchingTags.length) {
                reasons.push(
                    `tone:${matchingTags.join(',')}`,
                );
            }
            const role = String(
                profile.roleEn || '',
            );
            if (
                schoolContext &&
                /student/i.test(role)
            ) {
                score += 18;
                reasons.push(
                    'school_context',
                );
            }
            const band =
                profile.relativeAgeBand;
            if (
                agePreference ===
                    'peer_focused'
            ) {
                score += band === 'same_age'
                    ? 32
                    : [
                        'younger_peer',
                        'older_peer',
                    ].includes(band)
                        ? 10
                        : band ===
                            'older_generation'
                            ? -24
                            : -20;
            } else if (
                agePreference === 'mixed'
            ) {
                score += band === 'same_age'
                    ? 20
                    : [
                        'younger_peer',
                        'older_peer',
                    ].includes(band)
                        ? 14
                        : 2;
            } else {
                score +=
                    band ===
                        'older_generation'
                        ? 18
                        : band === 'same_age'
                            ? 10
                            : 8;
            }
            reasons.push(`age:${band}`);
            if (
                focuses.has('friendship') &&
                profile.settingTags.some(
                    tag => [
                        'social',
                        'compassionate',
                        'steady',
                    ].includes(tag))
            ) {
                score += 8;
            }
            if (
                focuses.has('rivalry') &&
                profile.settingTags.some(
                    tag => [
                        'ambitious',
                        'rebellious',
                    ].includes(tag))
            ) {
                score += 7;
            }
            if (
                focuses.has('romance') &&
                [
                    'same_age',
                    'younger_peer',
                    'older_peer',
                ].includes(band)
            ) {
                score += 7;
            }
            if (
                !profile.fixedBirthText
            ) {
                score -= 10;
            }
            return {
                ...profile,
                recommendationScore:
                    score,
                recommendationReasons:
                    reasons,
            };
        })
        .filter(Boolean)
        .sort((left, right) =>
            right.recommendationScore -
                left.recommendationScore ||
            left.nameEn.localeCompare(
                right.nameEn,
            ))
        .slice(
            0,
            Math.max(
                0,
                Number(limit) || 0,
            ),
        );
}
