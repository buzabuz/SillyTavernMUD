export function getCanonNameAliases(
    character,
) {
    const canonical =
        CANON_BY_ID.get(
            character?.id,
        ) || character;
    const nameEn = String(
        canonical?.nameEn ||
        character?.nameEn ||
        '',
    ).trim();
    const parts =
        nameEn.split(/\s+/u)
            .filter(Boolean);
    return [
        nameEn,
        canonical?.nameZh,
        character?.nameEn,
        character?.nameZh,
        ...(parts.length >= 3
            ? [
                `${parts[0]} ${parts.at(-1)}`,
            ]
            : []),
        ...(canonical?.aliasesZh || []),
        ...(character?.aliasesZh || []),
    ].filter(Boolean);
}

const CANON_BY_NAME = new Map();
CANON_CHARACTER_CATALOG.forEach(
    character => {
        const canonical =
            CANON_BY_ID.get(
                character.id,
            ) || character;
        getCanonNameAliases(character)
            .forEach(alias => {
                const key =
                    normalizeCanonName(
                        alias,
                    );
                if (!key) {
                    return;
                }
                const existing =
                    CANON_BY_NAME.get(key);
                CANON_BY_NAME.set(
                    key,
                    existing &&
                    existing.id !==
                        canonical.id
                        ? null
                        : canonical,
                );
            });
    },
);

export function findCanonCharacter(value) {
    const text = String(value || '').trim();
    return CANON_BY_ID.get(text) || CANON_BY_NAME.get(normalizeCanonName(text)) || null;
}

export function findMentionedCanonCharacters(text, limit = 12) {
    const normalized =
        normalizeCanonName(text);
    if (normalized.trim().length < 3) return [];
    const matches = [];
    const seenIds = new Set();
    CANON_CHARACTER_CATALOG
        .forEach(character => {
            const canonical =
                CANON_BY_ID.get(
                    character.id,
                ) || character;
            if (
                seenIds.has(
                    canonical.id,
                )
            ) {
                return;
            }
            const mentioned =
                getCanonNameAliases(
                    character,
                ).some(alias => {
                    const name =
                        normalizeCanonName(alias);
                    const isHan =
                        /[\p{Script=Han}]/u
                            .test(name);
                    if (
                        name.length <
                            (isHan ? 2 : 4) ||
                        CANON_BY_NAME.get(
                            name,
                        )?.id !==
                            canonical.id
                    ) {
                        return false;
                    }
                    return isHan
                        ? normalized.includes(name)
                        : ` ${normalized} `
                            .includes(
                                ` ${name} `,
                            );
                });
            if (mentioned) {
                seenIds.add(
                    canonical.id,
                );
                matches.push(
                    canonical,
                );
            }
        });
    return matches.slice(
        0,
        Math.max(
            0,
            Number(limit) || 0,
        ),
    );
}

